-- Run this once in the Supabase SQL Editor before deploying to Vercel.
create table if not exists public.sessions (
  session_id text primary key,
  route_id text not null,
  train_time text,
  train_direction text,
  started_at timestamptz not null,
  status text not null default 'active',
  finished_at timestamptz,
  visitor_id text
);

create table if not exists public.event_logs (
  id bigint generated by default as identity primary key,
  visitor_id text,
  session_id text not null,
  event_type text not null,
  timestamp timestamptz not null default now(),
  spot_id text,
  topic_id text,
  emotion text,
  utterance_id text,
  candidate_emotions jsonb not null default '[]'::jsonb,
  selection_weights jsonb not null default '{}'::jsonb,
  notification_played boolean,
  arrival_method text,
  payload jsonb not null default '{}'::jsonb
);

create index if not exists idx_events_session
  on public.event_logs(session_id);
create index if not exists idx_sessions_visitor
  on public.sessions(visitor_id);
create index if not exists idx_events_visitor_session
  on public.event_logs(visitor_id, session_id);

create unique index if not exists idx_event_unique_utterance
  on public.event_logs(session_id, event_type, utterance_id)
  where utterance_id is not null
    and event_type in ('utterance_shown', 'daily_utterance_shown', 'spot_utterance_shown', 'sulky_shown');
create unique index if not exists idx_event_unique_discovery
  on public.event_logs(session_id, spot_id)
  where event_type = 'spot_discovered' and spot_id is not null;
create unique index if not exists idx_event_unique_session_finish
  on public.event_logs(session_id)
  where event_type = 'session_finished';
create unique index if not exists idx_event_unique_return_guidance
  on public.event_logs(session_id)
  where event_type = 'return_guidance_started';

alter table public.sessions enable row level security;
alter table public.event_logs enable row level security;
grant all on table public.sessions, public.event_logs to service_role;
grant usage, select on sequence public.event_logs_id_seq to service_role;
